    // Хранилище WireGuard-туннелей: config\tunnels\<имя>.conf (стандартный формат WireGuard / WireSock)
    public static class Tunnels
    {
        public static string Dir { get { return Settings.Sub("tunnels"); } }

        public static List<string> Names()
        {
            try { return Directory.GetFiles(Dir, "*.conf").Select(Path.GetFileNameWithoutExtension).OrderBy(x => x, StringComparer.OrdinalIgnoreCase).ToList(); }
            catch { return new List<string>(); }
        }

        public static string PathOf(string name) { return Path.Combine(Dir, Safe(name) + ".conf"); }
        public static bool Exists(string name) { return !string.IsNullOrWhiteSpace(name) && File.Exists(PathOf(name)); }
        public static string Read(string name) { try { return File.ReadAllText(PathOf(name), Encoding.UTF8); } catch { return ""; } }
        public static void Write(string name, string text) { File.WriteAllText(PathOf(name), text.Replace("\r\n", "\n").Replace("\n", "\r\n"), new UTF8Encoding(false)); }
        public static void Delete(string name) { try { File.Delete(PathOf(name)); } catch { } }

        public static string Safe(string n)
        {
            var bad = Path.GetInvalidFileNameChars();
            var s = new string((n ?? "").Trim().Select(c => bad.Contains(c) ? '_' : c).ToArray());
            return s.Length == 0 ? "tunnel" : s;
        }

        public static string Endpoint(string name)
        {
            foreach (var l in Read(name).Split('\n'))
            {
                var t = l.Trim();
                if (t.StartsWith("Endpoint", StringComparison.OrdinalIgnoreCase) && t.Contains("=")) return t.Substring(t.IndexOf('=') + 1).Trim();
            }
            return "";
        }

        // Строит конфиг для запуска: убирает AllowedApps/DisallowedApps из исходника и подставляет списки маршрутизации.
        // disallowedIps — IP доменов «через DPI» (мимо туннеля), добавляются к DisallowedIPs из исходника
        public static string Runtime(string name, List<string> allowedApps, List<string> disallowedApps, bool dnsViaTunnel, List<string> disallowedIps = null)
        {
            var src = Read(name).Replace("\r", "").Split('\n');
            var dips = new List<string>();
            foreach (var raw in src)
            {
                var t = raw.Trim();
                if (t.Contains("=") && t.Substring(0, t.IndexOf('=')).Trim().Equals("DisallowedIPs", StringComparison.OrdinalIgnoreCase))
                    dips.AddRange(t.Substring(t.IndexOf('=') + 1).Split(',').Select(x => x.Trim()).Where(x => x.Length > 0));
            }
            if (disallowedIps != null) dips.AddRange(disallowedIps);
            dips = dips.Distinct(StringComparer.OrdinalIgnoreCase).ToList();
            var sb = new StringBuilder();
            sb.Append("# generated by NetProbe from ").Append(name).Append(".conf\r\n");
            string section = "";
            bool peerDone = false;
            Action addRules = () =>
            {
                if (allowedApps.Count > 0) sb.Append("AllowedApps = ").Append(string.Join(", ", allowedApps)).Append("\r\n");
                if (disallowedApps.Count > 0) sb.Append("DisallowedApps = ").Append(string.Join(", ", disallowedApps)).Append("\r\n");
                if (dips.Count > 0) sb.Append("DisallowedIPs = ").Append(string.Join(", ", dips)).Append("\r\n");
            };
            foreach (var raw in src)
            {
                var t = raw.Trim();
                if (t.StartsWith("["))
                {
                    if (section == "peer" && !peerDone) { addRules(); peerDone = true; }
                    section = t.Trim('[', ']').Trim().ToLowerInvariant();
                    sb.Append(t).Append("\r\n");
                    continue;
                }
                string key = t.Contains("=") ? t.Substring(0, t.IndexOf('=')).Trim().ToLowerInvariant() : "";
                if (key == "allowedapps" || key == "disallowedapps" || key == "disallowedips") continue;
                if (section == "interface" && key == "dns" && !dnsViaTunnel) continue;
                if (t.StartsWith("#") || t.Length == 0) continue;
                sb.Append(t).Append("\r\n");
            }
            if (section == "peer" && !peerDone) addRules();
            return sb.ToString();
        }

        // ---- импорт из TunnlTo (%APPDATA%\com.tunnl.to) ----
        public static string TunnlToDir { get { return Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData), "com.tunnl.to"); } }

        static Dictionary<string, object> Json(string file)
        {
            try { return new JavaScriptSerializer { MaxJsonLength = int.MaxValue }.Deserialize<Dictionary<string, object>>(File.ReadAllText(file, Encoding.UTF8)); }
            catch { return null; }
        }

        static object Get(object o, params string[] path)
        {
            foreach (var p in path) { var d = o as Dictionary<string, object>; if (d == null || !d.ContainsKey(p)) return null; o = d[p]; }
            return o;
        }

        static string Str(object o, params string[] path) { var v = Get(o, path); return v == null ? "" : Convert.ToString(v); }

        static List<string> StrList(object o)
        {
            var l = new List<string>();
            var a = o as IEnumerable; if (a == null || o is string) { if (o is string && (string)o != "") l.Add((string)o); return l; }
            foreach (var x in a) if (x != null) l.Add(Convert.ToString(x));
            return l;
        }

        // Возвращает отчёт об импорте. Ключи туннелей переносятся в config\tunnels как обычные .conf
        public static string ImportTunnlTo(out string firstName)
        {
            firstName = null;
            var rep = new StringBuilder();
            var ts = Json(Path.Combine(TunnlToDir, "tunnels_store.json"));
            var tunnels = Get(ts, "tunnels") as Dictionary<string, object>;
            string selected = Str(Json(Path.Combine(TunnlToDir, "app_data_store.json")), "appData", "enableTunnelState", "selectTunnel");
            int n = 0;
            if (tunnels != null)
            {
                foreach (var kv in tunnels)
                {
                    var t = kv.Value;
                    var wc = Get(t, "wireguardConfig");
                    if (wc == null) continue;
                    string name = Str(t, "name"); if (name == "") name = kv.Key;
                    var sb = new StringBuilder();
                    sb.Append("[Interface]\r\n");
                    sb.Append("PrivateKey = ").Append(Str(wc, "interface", "privateKey")).Append("\r\n");
                    var addr = StrList(Get(wc, "interface", "address")); if (addr.Count > 0) sb.Append("Address = ").Append(string.Join(", ", addr)).Append("\r\n");
                    var dns = StrList(Get(wc, "interface", "dns")); if (dns.Count > 0) sb.Append("DNS = ").Append(string.Join(", ", dns)).Append("\r\n");
                    string mtu = Str(wc, "interface", "mtu"); if (mtu != "") sb.Append("MTU = ").Append(mtu).Append("\r\n");
                    sb.Append("\r\n[Peer]\r\n");
                    sb.Append("PublicKey = ").Append(Str(wc, "peer", "publicKey")).Append("\r\n");
                    string psk = Str(wc, "peer", "presharedKey"); if (psk != "") sb.Append("PresharedKey = ").Append(psk).Append("\r\n");
                    string ep = Str(wc, "peer", "endpoint"), port = Str(wc, "peer", "port");
                    sb.Append("Endpoint = ").Append(ep).Append(port != "" && !ep.Contains(":") ? ":" + port : "").Append("\r\n");
                    string ka = Str(wc, "peer", "persistentKeepalive"); if (ka != "") sb.Append("PersistentKeepalive = ").Append(ka).Append("\r\n");
                    var aips = StrList(Get(wc, "peer", "allowedIPs"));
                    sb.Append("AllowedIPs = ").Append(aips.Count > 0 ? string.Join(", ", aips) : "0.0.0.0/0, ::/0").Append("\r\n");
                    Write(name, sb.ToString());
                    n++;
                    if (kv.Key == selected || firstName == null) firstName = Safe(name);
                    rep.Append(Tx("Туннель «")).Append(name).Append("» (").Append(ep).Append(")\r\n");
                }
            }
            // правила приложений: allowed -> «Приложения через VPN», disallowed -> исключения DPI/VPN
            var items = Get(Json(Path.Combine(TunnlToDir, "rule_items_store.json")), "ruleItems") as Dictionary<string, object>;
            var groups = Get(Json(Path.Combine(TunnlToDir, "rule_groups_store.json")), "ruleGroups") as Dictionary<string, object>;
            var state = Get(Json(Path.Combine(TunnlToDir, "app_data_store.json")), "appData", "enableTunnelState");
            Func<string, List<string>> collect = key =>
            {
                var ids = new List<string>(StrList(Get(state, key, "itemIds")));
                foreach (var g in StrList(Get(state, key, "groupIds")))
                    if (groups != null && groups.ContainsKey(g)) ids.AddRange(StrList(Get(groups[g], "rules")));
                var vals = new List<string>();
                foreach (var id in ids.Distinct())
                    if (items != null && items.ContainsKey(id)) { string v = Str(items[id], "value"); if (v != "" && !v.Contains("netprobe-")) vals.Add(v); }
                return vals;
            };
            if (state != null)
            {
                var allow = collect("allowed"); var deny = collect("disallowed");
                foreach (var a in allow) AppLists.Add(AppLists.HybridApps, a);
                foreach (var a in deny) AppLists.Add(AppLists.HybridExcl, a);
                rep.Append(Tx("Приложений через VPN: ")).Append(allow.Count).Append(Tx(", исключений: ")).Append(deny.Count).Append("\r\n");
            }
            if (n == 0 && state == null) return "";
            return Tx("Импортировано туннелей: ") + n + "\r\n" + rep;
        }
    }

    // Запуск wiresock-client.exe как дочернего процесса (run -config ...), разбор его вывода
    public class WiresockRunner
    {
        Process proc;
        readonly object lk = new object();
        public string TunnelName = "";
        public DateTime StartedAt, LastHandshake;
        public int Pid { get { lock (lk) { try { return proc != null && !proc.HasExited ? proc.Id : 0; } catch { return 0; } } } }
        public event Action<string> Output;
        public event Action<int> Exited;
        public bool Running { get { lock (lk) { try { return proc != null && !proc.HasExited; } catch { return false; } } } }

        public static string RuntimeFile { get { return Path.Combine(Settings.Sub("runtime"), "tunnel.conf"); } }

        public static bool ServiceRunning()
        {
            var r = Proc.Run("sc.exe", "query wiresock-client-service", 5000);
            return r.Out.Contains("RUNNING") || r.Out.Contains("START_PENDING");
        }

        public static bool StopService()
        {
            Proc.Run("sc.exe", "stop wiresock-client-service", 15000);
            for (int i = 0; i < 20; i++) { if (!ServiceRunning()) return true; Thread.Sleep(500); }
            return !ServiceRunning();
        }

        public static List<int> OtherInstances(int except)
        {
            var l = new List<int>();
            try { foreach (var p in Process.GetProcessesByName("wiresock-client")) { if (p.Id != except) l.Add(p.Id); p.Dispose(); } } catch { }
            return l;
        }

        public string Start(Settings st, string tunnel, string config)
        {
            Stop();
            if (!File.Exists(st.WiresockPath)) return Tx("Не найден wiresock-client.exe: ") + st.WiresockPath + Tx(". Установите WireSock VPN Client (есть в папке TunnlTo\\wiresock_installers) или укажите путь в Настройках.");
            try { File.WriteAllText(RuntimeFile, config, new UTF8Encoding(false)); }
            catch (Exception ex) { return Tx("Не удалось записать конфиг: ") + ex.Message; }
            string args = "run -config \"" + RuntimeFile + "\" -log-level " + st.WiresockLogLevel + (st.WiresockAdapter ? " -lac" : "");
            var psi = new ProcessStartInfo(st.WiresockPath, args)
            {
                // без перенаправления вывода: процесс не зависит от NetProbe и переживает его перезапуск при обновлении
                UseShellExecute = false, CreateNoWindow = true, WorkingDirectory = Path.GetDirectoryName(st.WiresockPath)
            };
            try
            {
                var p = new Process { StartInfo = psi, EnableRaisingEvents = true };
                p.OutputDataReceived += (s, e) => OnLine(e.Data);
                p.ErrorDataReceived += (s, e) => OnLine(e.Data);
                p.Exited += (s, e) =>
                {
                    int code = -1; try { code = p.ExitCode; } catch { }
                    bool mine; lock (lk) mine = proc == p;
                    if (mine) { var h = Exited; if (h != null) try { h(code); } catch { } }
                };
                p.Start();
                lock (lk) { proc = p; TunnelName = tunnel; StartedAt = DateTime.Now; LastHandshake = DateTime.MinValue; }
                return null;
            }
            catch (Exception ex) { return Tx("Не удалось запустить WireSock: ") + ex.Message; }
        }

        // Подхватить уже запущенный wiresock-client (после самообновления NetProbe)
        public void Attach(Process p, string tunnel)
        {
            p.EnableRaisingEvents = true;
            p.Exited += (s, e) => { int code = -1; try { code = p.ExitCode; } catch { } bool mine; lock (lk) mine = proc == p; if (mine) { var h = Exited; if (h != null) try { h(code); } catch { } } };
            lock (lk) { proc = p; TunnelName = tunnel; StartedAt = DateTime.Now; }
        }

        void OnLine(string s)
        {
            if (string.IsNullOrWhiteSpace(s)) return;
            if (s.IndexOf("Handshake response", StringComparison.OrdinalIgnoreCase) >= 0) LastHandshake = DateTime.Now;
            var h = Output; if (h != null) try { h(s.Trim()); } catch { }
        }

        [DllImport("kernel32.dll")] static extern bool AttachConsole(uint pid);
        [DllImport("kernel32.dll")] static extern bool FreeConsole();
        [DllImport("kernel32.dll")] static extern bool SetConsoleCtrlHandler(IntPtr h, bool add);
        [DllImport("kernel32.dll")] static extern bool GenerateConsoleCtrlEvent(uint ev, uint group);
        static readonly object ctrlLock = new object();

        // Мягкая остановка: Ctrl+C в консоль процесса (WireSock корректно снимает фильтр), затем принудительно
        public void Stop()
        {
            Process p;
            lock (lk) { p = proc; proc = null; }
            if (p == null) return;
            try
            {
                if (!p.HasExited)
                {
                    lock (ctrlLock)
                    {
                        try
                        {
                            FreeConsole();
                            if (AttachConsole((uint)p.Id))
                            {
                                SetConsoleCtrlHandler(IntPtr.Zero, true);
                                GenerateConsoleCtrlEvent(0, 0);
                                FreeConsole();
                                p.WaitForExit(5000);
                                SetConsoleCtrlHandler(IntPtr.Zero, false);
                            }
                        }
                        catch { }
                    }
                    if (!p.HasExited) { try { p.Kill(); } catch { } p.WaitForExit(3000); }
                }
            }
            catch { }
            try { p.Dispose(); } catch { }
        }
    }
